package com.alfgoto.rune.visuals.menu;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import net.kyori.adventure.key.Key;

/**
 * The fonts used to draw live text and bars in menus (docs/art-direction.md, "Menus"). Their glyph sheets
 * and widths come from {@code /menu_font.json}, written by {@code tools/texture-gen/v3/menufont.py}.
 *
 * <p>A bitmap font row sits at one height only, so there is one font per family and per height:
 * {@code rune:menu/<family>_<y>}, generated by {@link #packFiles()} when the resource pack is built.
 * {@code y} is the top of the capitals, in pixels from the top of the menu window.
 */
public enum MenuFont {
    /** Vanilla-looking text with French / Latin accents. */
    NORMAL("normal"),
    /** {@link #NORMAL} with a drop shadow, for light text on dark backgrounds. */
    SHADOW("shadow"),
    /** 3x5 capitals: numbers and text too wide for {@link #NORMAL}. Upper-cased, accents dropped. */
    SMALL("small"),
    /** Progress-bar pieces (see {@link MenuCanvas#bar}). */
    BARS("bars");

    /** Lowest and highest text top (window pixels) a font is generated for. */
    public static final int MIN_Y = 3;

    public static final int MAX_Y = 140;

    /** The title starts 13 px below where a font with ascent 0 would put the top of its glyphs. */
    static final int TITLE_BASE = 13;

    private static final Map<String, Data> DATA = load();

    private final String id;

    MenuFont(String id) {
        this.id = id;
    }

    public String id() {
        return id;
    }

    /** The font that draws this family with its capitals' top at {@code y}. */
    public Key key(int y) {
        if (y < MIN_Y || y > MAX_Y) {
            throw new IllegalArgumentException("menu text y must be " + MIN_Y + " to " + MAX_Y + ", got " + y);
        }
        return Key.key("rune", "menu/" + id + "_" + y);
    }

    /** {@code text} as this font can draw it: SMALL is upper-case; unknown characters lose their accent or become '?'. */
    public String normalize(String text) {
        Data data = data();
        String source = this == SMALL ? stripAccents(text.toUpperCase(Locale.ROOT)) : text;
        StringBuilder out = new StringBuilder(source.length());
        for (int i = 0; i < source.length(); i++) {
            char c = source.charAt(i);
            if (c == ' ' || data.advances.containsKey(c)) {
                out.append(c);
            } else {
                String base = stripAccents(String.valueOf(c));
                char b = base.isEmpty() ? '?' : base.charAt(0);
                out.append(data.advances.containsKey(b) ? b : '?');
            }
        }
        return out.toString();
    }

    /** How far the title cursor moves after drawing {@code text} (already {@link #normalize normalized}). */
    public int advance(String text) {
        Data data = data();
        int total = 0;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            total += c == ' ' ? data.space : data.advances.getOrDefault(c, 0);
        }
        return total;
    }

    /** The visible width of {@code text}: its advance minus the 1 px gap after the last glyph. */
    public int width(String text) {
        String normalized = normalize(text);
        return Math.max(0, advance(normalized) - (normalized.isEmpty() ? 0 : 1));
    }

    /** Pixels between the top of a glyph cell and the top of the capitals. */
    int capTop() {
        return data().capTop;
    }

    private Data data() {
        Data data = DATA.get(id);
        if (data == null) {
            throw new IllegalStateException("menu_font.json has no family " + id);
        }
        return data;
    }

    /** Every generated font file of the pack: {@code assets/rune/font/menu/<family>_<y>.json} → JSON. */
    public static Map<String, String> packFiles() {
        Map<String, String> files = new LinkedHashMap<>();
        Gson gson = new Gson();
        for (MenuFont font : values()) {
            Data data = font.data();
            for (int y = MIN_Y; y <= MAX_Y; y++) {
                JsonArray providers = new JsonArray();
                if (data.space > 0) {
                    JsonObject space = new JsonObject();
                    space.addProperty("type", "space");
                    JsonObject advances = new JsonObject();
                    advances.addProperty(" ", data.space);
                    space.add("advances", advances);
                    providers.add(space);
                }
                JsonObject bitmap = new JsonObject();
                bitmap.addProperty("type", "bitmap");
                bitmap.addProperty("file", data.file);
                bitmap.addProperty("height", data.height);
                bitmap.addProperty("ascent", TITLE_BASE - y + data.capTop);
                JsonArray chars = new JsonArray();
                data.chars.forEach(chars::add);
                bitmap.add("chars", chars);
                providers.add(bitmap);
                JsonObject root = new JsonObject();
                root.add("providers", providers);
                files.put("assets/rune/font/menu/" + font.id + "_" + y + ".json", gson.toJson(root) + "\n");
            }
        }
        return files;
    }

    private static String stripAccents(String text) {
        return Normalizer.normalize(text, Normalizer.Form.NFD).replaceAll("\\p{M}", "");
    }

    private record Data(
            String file, int height, int capTop, int space, List<String> chars, Map<Character, Integer> advances) {}

    private static Map<String, Data> load() {
        try (InputStream in = MenuFont.class.getResourceAsStream("/menu_font.json")) {
            if (in == null) {
                throw new IOException("Missing resource /menu_font.json");
            }
            JsonObject root = new Gson().fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
            Map<String, Data> out = new HashMap<>();
            for (Map.Entry<String, JsonElement> family : root.entrySet()) {
                JsonObject f = family.getValue().getAsJsonObject();
                List<String> chars = new ArrayList<>();
                f.getAsJsonArray("chars").forEach(e -> chars.add(e.getAsString()));
                Map<Character, Integer> advances = new HashMap<>();
                for (Map.Entry<String, JsonElement> a : f.getAsJsonObject("advances").entrySet()) {
                    advances.put(a.getKey().charAt(0), a.getValue().getAsInt());
                }
                out.put(
                        family.getKey(),
                        new Data(
                                f.get("file").getAsString(),
                                f.get("height").getAsInt(),
                                f.get("capTop").getAsInt(),
                                f.get("space").getAsInt(),
                                chars,
                                advances));
            }
            return out;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
