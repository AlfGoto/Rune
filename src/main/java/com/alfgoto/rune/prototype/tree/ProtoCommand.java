package com.alfgoto.rune.prototype.tree;

import com.alfgoto.rune.command.Subcommand;
import com.alfgoto.rune.prototype.tree.ProtoTreeData.Job;
import io.papermc.paper.datapack.Datapack;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import net.kyori.adventure.key.Key;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.format.NamedTextColor;
import org.bukkit.Bukkit;
import org.bukkit.NamespacedKey;
import org.bukkit.advancement.Advancement;
import org.bukkit.advancement.AdvancementProgress;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;
import org.bukkit.plugin.java.JavaPlugin;

/**
 * THROWAWAY (issue #138). {@code /rune proto tree <loadAdvancement|datapack|library>},
 * {@code ... award <job> <n>}, {@code ... revoke <job> <n>}.
 *
 * <p>Each approach has its own namespace, so both tabs can sit side by side in the {@code L} screen.
 */
final class ProtoCommand implements Subcommand {

    private static final String LOAD_NS = "rune_load";
    private static final String PACK_NS = "rune_pack";
    private static final String PACK_NAME = "rune_proto";
    private static final List<String> APPROACHES = List.of("loadAdvancement", "datapack", "library");

    private final JavaPlugin plugin;

    ProtoCommand(JavaPlugin plugin) {
        this.plugin = plugin;
    }

    @Override
    public String name() {
        return "proto";
    }

    @Override
    public void execute(CommandSender sender, List<String> args) {
        if (args.isEmpty() || !args.getFirst().equalsIgnoreCase("tree") || args.size() < 2) {
            usage(sender);
            return;
        }
        String action = args.get(1).toLowerCase(Locale.ROOT);
        switch (action) {
            case "loadadvancement" -> loadAdvancement(sender);
            case "datapack" -> datapack(sender);
            case "library" -> say(sender, "The library approach is not built in this prototype. See the PR.",
                    NamedTextColor.YELLOW);
            case "award", "revoke" -> change(sender, action.equals("award"), args);
            default -> usage(sender);
        }
    }

    @Override
    public List<String> complete(CommandSender sender, List<String> args) {
        List<String> options = new ArrayList<>();
        if (args.size() == 1) {
            options.add("tree");
        } else if (args.size() == 2) {
            options.addAll(APPROACHES);
            options.addAll(List.of("award", "revoke"));
        } else if (args.size() == 3 && List.of("award", "revoke").contains(args.get(1).toLowerCase(Locale.ROOT))) {
            ProtoTreeData.JOBS.forEach(job -> options.add(job.id()));
        } else if (args.size() == 4) {
            options.addAll(List.of("1", "2", "3", "4"));
        }
        String typed = args.getLast().toLowerCase(Locale.ROOT);
        return options.stream().filter(o -> o.toLowerCase(Locale.ROOT).startsWith(typed)).toList();
    }

    // ---- approach 1: Paper loadAdvancement at runtime ----

    private void loadAdvancement(CommandSender sender) {
        Map<Key, String> json = new LinkedHashMap<>();
        ProtoTreeData.build("Rune (loadAdvancement)")
                .forEach((path, body) -> json.put(Key.key(LOAD_NS, path), ProtoTreeData.withNamespace(body, LOAD_NS)));
        try {
            // persist = false: lives in memory only, gone after a restart or /reload.
            var loaded = Bukkit.getUnsafe().loadAdvancements(json, false);
            say(sender, "loadAdvancement: loaded " + loaded.size() + " of " + json.size() + " advancements.",
                    NamedTextColor.GREEN);
        } catch (Exception e) {
            say(sender, "loadAdvancement failed (already loaded?): " + e, NamedTextColor.RED);
        }
        activate(LOAD_NS);
        say(sender, "Press L. If the tab is missing, relog and tell Alf.", NamedTextColor.GRAY);
    }

    // ---- approach 2: datapack generated by the plugin ----

    private void datapack(CommandSender sender) {
        Path pack = Bukkit.getWorldContainer().toPath()
                .resolve(Bukkit.getUnsafe().getMainLevelName())
                .resolve("datapacks")
                .resolve(PACK_NAME);
        try {
            Path dir = pack.resolve("data").resolve(PACK_NS).resolve("advancement");
            Files.createDirectories(dir);
            Files.writeString(pack.resolve("pack.mcmeta"), """
                    {"pack":{"description":"Rune Unlock Tree prototype","min_format":82,"max_format":9999}}
                    """, StandardCharsets.UTF_8);
            for (var entry : ProtoTreeData.build("Rune (datapack)").entrySet()) {
                Files.writeString(dir.resolve(entry.getKey() + ".json"),
                        ProtoTreeData.withNamespace(entry.getValue(), PACK_NS), StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            say(sender, "datapack: could not write " + pack + ": " + e, NamedTextColor.RED);
            return;
        }
        Bukkit.getDatapackManager().refreshPacks();
        Datapack found = Bukkit.getDatapackManager().getPack("file/" + PACK_NAME);
        if (found == null) {
            say(sender, "datapack: written to " + pack + " but the server did not discover it. "
                    + "Try /minecraft:reload or a restart.", NamedTextColor.RED);
            return;
        }
        found.setEnabled(true);
        say(sender, "datapack: written to " + pack + " and enabled. Reloading data...", NamedTextColor.GREEN);
        // The reload is not instant: wait a moment, then unlock the root and the Job icons.
        plugin.getServer().getScheduler().runTaskLater(plugin, () -> {
            activate(PACK_NS);
            say(sender, "datapack: ready. Press L.", NamedTextColor.GREEN);
        }, 60L);
    }

    // ---- award / revoke (same Bukkit API for both approaches) ----

    private void change(CommandSender sender, boolean award, List<String> args) {
        if (!(sender instanceof Player player)) {
            say(sender, "Only a player can do this.", NamedTextColor.RED);
            return;
        }
        Job job = args.size() == 4 ? ProtoTreeData.job(args.get(2).toLowerCase(Locale.ROOT)) : null;
        int n = args.size() == 4 ? parse(args.get(3)) : -1;
        if (job == null || n < 1 || n > job.nodes().size()) {
            usage(sender);
            return;
        }
        int changed = 0;
        // award n: nodes 1..n unlocked. revoke n: node n and everything after it locked again.
        int from = award ? 1 : n;
        int to = award ? n : job.nodes().size();
        for (String ns : List.of(LOAD_NS, PACK_NS)) {
            for (int i = from; i <= to; i++) {
                AdvancementProgress progress = progress(player, ns, ProtoTreeData.node(job, i));
                if (progress == null) {
                    continue;
                }
                boolean did = award
                        ? progress.awardCriteria(ProtoTreeData.CRITERION)
                        : progress.revokeCriteria(ProtoTreeData.CRITERION);
                if (did) {
                    changed++;
                }
            }
        }
        say(sender, (award ? "Awarded " : "Revoked ") + changed + " node(s) on " + job.name()
                + (changed == 0 ? " (nothing changed, or no tab loaded: run an approach first)." : "."),
                NamedTextColor.GREEN);
    }

    /** Root and Job icons: unlocked silently so the tab shows (their toast is off). */
    private void activate(String namespace) {
        for (Player player : Bukkit.getOnlinePlayers()) {
            List<String> paths = new ArrayList<>();
            paths.add(ProtoTreeData.ROOT);
            ProtoTreeData.JOBS.forEach(job -> paths.add(ProtoTreeData.head(job)));
            for (String path : paths) {
                AdvancementProgress progress = progress(player, namespace, path);
                if (progress != null) {
                    progress.awardCriteria(ProtoTreeData.CRITERION);
                }
            }
        }
    }

    private static AdvancementProgress progress(Player player, String namespace, String path) {
        Advancement advancement = Bukkit.getAdvancement(new NamespacedKey(namespace, path));
        return advancement == null ? null : player.getAdvancementProgress(advancement);
    }

    private static int parse(String text) {
        try {
            return Integer.parseInt(text);
        } catch (NumberFormatException e) {
            return -1;
        }
    }

    private static void usage(CommandSender sender) {
        say(sender, "Usage: /rune proto tree <loadAdvancement|datapack|library> | award <job> <n> | revoke <job> <n>",
                NamedTextColor.RED);
    }

    // Throwaway admin output: plain text on purpose, deleted with the prototype.
    private static void say(CommandSender sender, String text, NamedTextColor color) {
        sender.sendMessage(Component.text(text, color));
    }
}
